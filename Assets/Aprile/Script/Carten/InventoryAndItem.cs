// =========================================================================================
// [1. 네임스페이스(Namespace) 불러오기]
// =========================================================================================
using System.Collections.Generic; // List<T> 같은 가변 크기 자료구조를 사용하기 위해 필수
using UnityEngine;              // 유니티 기본 클래스(MonoBehaviour, Debug, Mathf 등) 사용

// =========================================================================================
// [2. 열거형 (enum : Enumeration)]
// - 개념: 연관된 아이템 종류에 직관적인 이름을 부여한 데이터 타입입니다.
// - 이유: 0, 1, 2 대신 DropItemType.Heal, DropItemType.Money 처럼 가독성 있게 표현합니다.
// =========================================================================================
public enum DropItemType
{
    Heal,       // 0번: 생명력 회복 아이템
    Invincible, // 1번: 일정 시간 무적 아이템
    DefenseUp,  // 2번: 일정 시간 방어력 강화 아이템
    Money       // 3번: 파편(돈) - 가방에 안 들어가고 즉시 습득되는 특수 아이템
}

// =========================================================================================
// [3. 아이템 데이터 클래스 & 직렬화]
// - [System.Serializable]: 이 클래스의 데이터를 유니티 인스펙터(Inspector) 창에 표시하고
//   데이터 저장이 가능하도록 직렬화를 허가하는 어트리뷰트입니다.
// - 클래스(Class): 아이템의 '종류(type)', '무게(weight)', '효과값(value)'을 하나로 묶는 틀입니다.
// =========================================================================================
[System.Serializable]
public class InventoryItem
{
    public DropItemType itemType; // 아이템의 종류 (Enum)
    public float weight;          // 아이템 개별 무게 (float: 소수점 포함 실수 타입)
    public float value;           // 회복량, 무적 시간, 방어력 증가량 등 효과 숫자
}

// =========================================================================================
// [4. InventoryAndItem 메인 클래스]
// - MonoBehaviour 상속: 게임 오브젝트에 컴포넌트로 붙어 작동할 수 있게 해줍니다.
// =========================================================================================
public class InventoryAndItem : MonoBehaviour
{
    // -------------------------------------------------------------------------------------
    // [싱글톤 패턴 (Singleton Pattern)]
    // - InventoryAndItem.Instance 로 어디서나 쉽게 인벤토리에 접근할 수 있게 만듭니다.
    // - { get; private set; }: 읽기는 누구나 가능하지만, Instance 대입은 내부에서만 수행합니다.
    // -------------------------------------------------------------------------------------
    public static InventoryAndItem Instance { get; private set; }

    // [Header("...")] : 인스펙터 창에서 변수 구분을 쉽게 하도록 타이틀을 달아주는 기능
    [Header("가방 제한 설정 (기획서 5-2)")]
    public int maxItemCount = 5;       // 가방에 들어갈 수 있는 최대 아이템 개수 (int: 정수)
    public float maxWeightLimit = 10f; // 가방이 견딜 수 있는 최대 무게 (float: 실수)

    // List<InventoryItem>: 가방 안에 들어있는 InventoryItem 객체들의 가변 목록
    public List<InventoryItem> bag = new List<InventoryItem>();

    // -------------------------------------------------------------------------------------
    // [C# 자동 구현 프로퍼티 (Property)]
    // - CurrentWeight: 현재 가방 안 아이템들의 총무게
    // - { get; private set; } = 0f;
    //   -> 외부 스크립트에서는 CurrentWeight 값을 '읽기'만 할 수 있고,
    //      '값 변경'은 이 클래스 내부(CurrentWeight += weight)에서만 가능하도록 안전하게 보호합니다.
    // -------------------------------------------------------------------------------------
    public float CurrentWeight { get; private set; } = 0f;

    // -------------------------------------------------------------------------------------
    // [Awake() : 유니티 초기화 생명주기]
    // - 오브젝트가 생성될 때 가장 먼저 실행되어 싱글톤 인스턴스를 등록합니다.
    // -------------------------------------------------------------------------------------
    private void Awake()
    {
        if (Instance == null) Instance = this; // 내가 최초 인스턴스라면 정적 변수에 할당
    }

    // -------------------------------------------------------------------------------------
    // [아이템 획득 시도 메서드]
    // - 반환 타입 bool: 아이템 획득 성공 시 true, 실패(가방 가득 차거나 무게 초과) 시 false 반환
    // -------------------------------------------------------------------------------------
    public bool TryAddItemToBag(DropItemType type, float weight, float value)
    {
        // ---------------------------------------------------------------------------------
        // [예외 처리 1: 돈(Money) 아이템]
        // - 돈은 가방 칸이나 무게를 차지하지 않고 즉시 DataManager의 money로 흡수됩니다.
        // ---------------------------------------------------------------------------------
        if (type == DropItemType.Money)
        {
            // Null 체크: DataManager가 메모리에 정상적으로 존재할 때만 접근하여 에러 방지
            if (DataManager.Instance != null)
            {
                // Mathf.RoundToInt(float): 실수(float) 데이터를 소수점 반올림하여 정수(int)로 변환
                // (money 변수가 int 타입이므로 형변환이 필요함)
                DataManager.Instance.money += Mathf.RoundToInt(value);
            }
            return true; // 돈 습득 성공 처리 후 함수 즉시 종료 (가방에 추가하지 않음)
        }

        // ---------------------------------------------------------------------------------
        // [예외 처리 2: 가방 개수 제한 검사 (Guard Clause)]
        // - 현재 가방의 아이템 개수(bag.Count)가 최대 허용 개수 이상이면 획득 실패
        // ---------------------------------------------------------------------------------
        if (bag.Count >= maxItemCount)
        {
            Debug.Log("가방의 개수 제한을 초과하여 아이템을 획득할 수 없습니다!");
            return false; // 획득 실패 반환 후 함수 종료
        }

        // ---------------------------------------------------------------------------------
        // [예외 처리 3: 가방 무게 제한 검사 (Guard Clause)]
        // - (현재 총무게 + 새 아이템 무게)가 최대 무게 제한을 초과하면 획득 실패
        // ---------------------------------------------------------------------------------
        if (CurrentWeight + weight > maxWeightLimit)
        {
            Debug.Log("가방의 무게 제한을 초과하여 아이템을 획득할 수 없습니다!");
            return false; // 획득 실패 반환 후 함수 종료
        }

        // ---------------------------------------------------------------------------------
        // [아이템 최종 습득 처리]
        // 1. 객체 초기화 문법: new InventoryItem { ... } 으로 새 아이템 객체를 생성하여 bag 리스트에 추가
        // 2. CurrentWeight 증가: 현재 무게 누적 업데이트
        // ---------------------------------------------------------------------------------
        bag.Add(new InventoryItem { itemType = type, weight = weight, value = value });
        CurrentWeight += weight;

        // 문자열 보간($"..."): 현재 상태 로그 출력
        Debug.Log($"{type} 아이템 습득! (현재 개수: {bag.Count}/{maxItemCount}, 무게: {CurrentWeight}/{maxWeightLimit})");
        return true; // 아이템 습득 성공 반환
    }
}