// =========================================================================================
// [1. 네임스페이스(Namespace) 불러오기]
// =========================================================================================
using UnityEngine; // 유니티 기본 클래스(MonoBehaviour, Random, Vector2, Time 등) 사용

// =========================================================================================
// [2. Obstacle 메인 클래스]
// - 필드 상의 운석/장애물 게임 오브젝트에 부착되는 스크립트입니다.
// =========================================================================================
public class Obstacle : MonoBehaviour
{
    // [Header("...")] : 유니티 인스펙터(Inspector) 창에서 변수 카테고리를 시각적으로 구분해주는 속성
    [Header("운석 이동 및 회전 설정")]
    public float moveSpeed = 2.5f;   // 이동 속도 (float: 실수 타입)
    public float rotateSpeed = 45f;  // 초당 자전 회전 속도 (각도/초)

    // Vector2: X, Y 2개의 축을 가지는 2차원 좌표/방향 데이터 타입
    // 화면 경계의 최소(좌측 하단), 최대(우측 상단) 좌표 설정
    public Vector2 minBounds = new Vector2(-8.5f, -5f); // X: -8.5, Y: -5
    public Vector2 maxBounds = new Vector2(8.5f, 5f);   // X: 8.5, Y: 5

    // private: 외부 스크립트에서 접근할 수 없도록 이 클래스 내부로 숨김
    private Vector2 moveDirection; // 장애물이 현재 이동 중인 방향 벡터 (크기 1인 단위 벡터)

    // -------------------------------------------------------------------------------------
    // [Start() : 유니티 초기화 생명주기]
    // - 오브젝트가 생성될 때 딱 1번 실행되어 초기 이동 방향을 결정합니다.
    // -------------------------------------------------------------------------------------
    private void Start()
    {
        // 1. Random.insideUnitCircle: 반지름 1짜리 원 내부의 임의의 2D 점(Vector2)을 반환
        // 2. .normalized: 벡터의 방향만 남기고 '길이(크기)를 무조건 1'로 만들어 줍니다. (단위 벡터화)
        moveDirection = Random.insideUnitCircle.normalized;

        // 예외 처리 (Safeguard): 혹시라도 뽑힌 랜덤 값이 (0,0)이라 이동하지 않는 상황 방지
        if (moveDirection == Vector2.zero) moveDirection = Vector2.down; // 아래쪽 방향으로 기본 설정
    }

    // -------------------------------------------------------------------------------------
    // [Update() : 유니티 매 프레임 생명주기]
    // - 화면이 새로 고쳐질 때마다(매 프레임) 지속적으로 실행되어 이동, 회전, 벽 충돌을 처리합니다.
    // -------------------------------------------------------------------------------------
    private void Update()
    {
        // ---------------------------------------------------------------------------------
        // [1. 위치 이동 연출]
        // - Time.deltaTime: 전 프레임에서 현재 프레임까지 걸린 시간(초)
        //   -> 프레임 속도(FPS)가 다른 컴퓨터에서도 동일한 속도로 이동하게 만드는 '프레임 독립성' 제공
        // - (Vector3): Vector2 데이터 타입을 3D 좌표계 타입(Vector3)으로 명시적 형변환(Casting)
        // ---------------------------------------------------------------------------------
        transform.position += (Vector3)(moveDirection * moveSpeed * Time.deltaTime);

        // ---------------------------------------------------------------------------------
        // [2. 자전 회전 연출]
        // - transform.Rotate(x, y, z): Z축 기준으로 매 초 rotateSpeed 만큼 자전 회전시킴
        // ---------------------------------------------------------------------------------
        transform.Rotate(0f, 0f, rotateSpeed * Time.deltaTime);

        // ---------------------------------------------------------------------------------
        // [3. 화면 경계 벽 반사(Bounce) 및 경계 제한 처리]
        // ---------------------------------------------------------------------------------
        Vector3 pos = transform.position; // 현재 오브젝트의 위치 복사

        // X축(좌/우) 화면 경계 체크
        if (pos.x <= minBounds.x || pos.x >= maxBounds.x)
        {
            moveDirection.x = -moveDirection.x; // X축 방향을 반대로 반전 (좌 -> 우, 우 -> 좌)

            // Mathf.Clamp(현재값, 최소값, 최대값): pos.x가 minBounds.x ~ maxBounds.x 범위를 벗어나지 않게 고정
            // (벽 밖으로 뚫고 나가는 현상을 완전 차단)
            pos.x = Mathf.Clamp(pos.x, minBounds.x, maxBounds.x);
        }

        // Y축(상/하) 화면 경계 체크
        if (pos.y <= minBounds.y || pos.y >= maxBounds.y)
        {
            moveDirection.y = -moveDirection.y; // Y축 방향을 반대로 반전 (위 -> 아래, 아래 -> 위)
            pos.y = Mathf.Clamp(pos.y, minBounds.y, maxBounds.y);
        }

        // 튕김 계산 및 위치 제한이 완료된 최종 좌표를 실제 오브젝트 위치에 적용
        transform.position = pos;
    }
}